# Scenarios
# ---------------------------------------------------------------------------


def make_balanced_hands_a() -> dict[Seat, list[Card]]:
    """Diverse-suit hands: trumper (West) has clubs lead and a non-club."""
    layout = {
        Seat.NORTH: ["9h", "Ah", "10h", "Kh", "Qh", "8h", "7h", "Js"],
        Seat.WEST:  ["Jc", "9c", "Ac", "Kc", "Qd", "8c", "7c", "Jh"],
        Seat.SOUTH: ["10c", "9d", "Ad", "10d", "Kd", "Jd", "8d", "7d"],
        Seat.EAST:  ["9s", "As", "10s", "Ks", "Qs", "8s", "7s", "Qc"],
    }
    hands = {seat: [Card.from_str(c) for c in cs] for seat, cs in layout.items()}
    # Verify pack completeness.
    seen = sorted(str(c) for cs in hands.values() for c in cs)
    expected = sorted(
        f"{r}{s}" for s in "cdhs"
        for r in ["J", "9", "A", "10", "K", "Q", "8", "7"]
    )
    if seen != expected:
        raise ValueError(f"Layout invalid. Got {seen}; expected {expected}")
    return hands


def scenario_happy_closed_trump() -> dict[str, Any]:
    """Closed-trump game: West bids 160 on Jc. 8-card all pass. Closed play."""
    hands = make_balanced_hands_a()
    scripted: list[dict[str, Any]] = [
        # 4-card betting: order west, south, east, north.
        {"type": "bid", "seat": "west", "action": "bet", "value": 160},
        {"type": "bid", "seat": "south", "action": "pass"},
        {"type": "bid", "seat": "east", "action": "pass"},
        {"type": "bid", "seat": "north", "action": "pass"},
        # Trump select.
        {"type": "select_trump", "seat": "west", "card": "Jc"},
        # 8-card betting all pass.
        {"type": "bid", "seat": "west", "action": "pass"},
        {"type": "bid", "seat": "south", "action": "pass"},
        {"type": "bid", "seat": "east", "action": "pass"},
        {"type": "bid", "seat": "north", "action": "pass"},
        # Closed trump.
        {"type": "closed_trump", "seat": "west"},
    ]
    return build_fixture(
        "happy_closed_trump", hands, Seat.NORTH, scripted,
        auto_play_until_complete=True,
    )


def scenario_open_trump() -> dict[str, Any]:
    """Open-trump variant: West declares Open Trump before play."""
    hands = make_balanced_hands_a()
    scripted: list[dict[str, Any]] = [
        {"type": "bid", "seat": "west", "action": "bet", "value": 160},
        {"type": "bid", "seat": "south", "action": "pass"},
        {"type": "bid", "seat": "east", "action": "pass"},
        {"type": "bid", "seat": "north", "action": "pass"},
        {"type": "select_trump", "seat": "west", "card": "Jc"},
        {"type": "bid", "seat": "west", "action": "pass"},
        {"type": "bid", "seat": "south", "action": "pass"},
        {"type": "bid", "seat": "east", "action": "pass"},
        {"type": "bid", "seat": "north", "action": "pass"},
        {"type": "open_trump", "seat": "west", "revealCard": "9c"},
    ]
    return build_fixture(
        "open_trump", hands, Seat.NORTH, scripted,
        auto_play_until_complete=True,
    )


def scenario_pass_on() -> dict[str, Any]:
    """4-card pass-on: all 4 players pass; deal moves to next dealer."""
    hands = make_balanced_hands_a()
    scripted: list[dict[str, Any]] = [
        {"type": "bid", "seat": "west", "action": "pass"},
        {"type": "bid", "seat": "south", "action": "pass"},
        {"type": "bid", "seat": "east", "action": "pass"},
        {"type": "bid", "seat": "north", "action": "pass"},
    ]
    return build_fixture(
        "pass_on_4_card", hands, Seat.NORTH, scripted,
        auto_play_until_complete=False,
    )


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------


def main() -> None:
    os.makedirs(OUT_DIR, exist_ok=True)
    fixtures = [
        scenario_happy_closed_trump(),
        scenario_open_trump(),
        scenario_pass_on(),
    ]
    for fix in fixtures:
        out_path = os.path.join(OUT_DIR, f"{fix['name']}.json")
        with open(out_path, "w") as f:
            json.dump(fix, f, indent=2, sort_keys=True)
        print(f"wrote {out_path}  ({len(fix['checkpoints'])} checkpoints)")


if __name__ == "__main__":
    main()
